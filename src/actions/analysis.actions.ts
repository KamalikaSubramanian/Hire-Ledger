/* =========================================================
   HELPER
========================================================= */

function extractJson(text: string) {
  try {
    return JSON.parse(text);
  } catch {
    const cleaned = text
      .replace(/```json/g, "")
      .replace(/```/g, "")
      .trim();

    return JSON.parse(cleaned);
  }
}

/* =========================================================
   ANALYZE RESUME
========================================================= */

export async function analyzeResume(applicationId: string) {
  try {
    await connectDB();

    const user = await syncUser();

    if (!user.success || !user.data) {
      return {
        success: false,
        message: "Unauthorized",
      };
    }

    /* -------------------------------------------------------
       FIND APPLICATION
    ------------------------------------------------------- */

    const application = await Application.findOne({
      _id: applicationId,
      userId: user.data._id,
    });

    if (!application) {
      return {
        success: false,
        message: "Application not found.",
      };
    }

    /* -------------------------------------------------------
       CHECK RESUME
    ------------------------------------------------------- */

    if (!application.resumeId) {
      return {
        success: false,
        message: "Resume not selected.",
      };
    }

    const resume = await Resume.findById(application.resumeId);

    if (!resume) {
      return {
        success: false,
        message: "Resume not found.",
      };
    }

    /* =======================================================
       DOWNLOAD RESUME PDF
    ======================================================= */

    const fileResponse = await fetch(resume.url);

    if (!fileResponse.ok) {
      return {
        success: false,
        message: "Unable to download resume.",
      };
    }

    const arrayBuffer = await fileResponse.arrayBuffer();

    const pdfBase64 = Buffer.from(arrayBuffer).toString("base64");

    /* =======================================================
       ASK GEMINI
    ======================================================= */

    const geminiResponse = await ai.models.generateContent({
      model: "gemini-flash-latest",

      contents: [
        {
          inlineData: {
            mimeType: "application/pdf",
            data: pdfBase64,
          },
        },

        {
          text: `
${resumeAnalysisPrompt}

Job Description

${application.jobDescription}
`,
        },
      ],
    });

    const responseText = geminiResponse.text?.trim();

    if (!responseText) {
      return {
        success: false,
        message: "Gemini returned an empty response.",
      };
    }

    /* =======================================================
       PARSE GEMINI RESPONSE
    ======================================================= */

    let result: any;

    try {
      result = extractJson(responseText);
    } catch (error) {
      console.error("Gemini JSON Parse Error");
      console.log(responseText);

      return {
        success: false,
        message: "Unable to parse AI response.",
      };
    }

    /* =======================================================
       VALIDATE AI RESPONSE
    ======================================================= */

    if (
      !result.resumeHealth ||
      !result.atsAnalysis ||
      !result.jobMatch ||
      !result.sectionReview
    ) {
      return {
        success: false,
        message: "Invalid analysis received from Gemini.",
      };
    }

    /* =======================================================
       CREATE ANALYSIS
       
       createdAt will be automatically generated by Mongoose
       if timestamps: true is enabled in Analysis schema.
    ======================================================= */

    const analysis = await Analysis.create({
      userId: user.data._id,

      applicationId: application._id,

      resumeId: resume._id,

      company: application.company,

      jobTitle: application.jobTitle,

      location: application.location,

      appliedDate: application.appliedDate,

      status: application.status,

      resumeName: resume.fileName,

      resumeUrl: resume.url,

      jobDescription: application.jobDescription,

      analysisTitle: `${application.company} - ${application.jobTitle}`,

      analysisResult: result,
    });

    /* =======================================================
       UPDATE APPLICATION STATUS
    ======================================================= */

    await Application.findByIdAndUpdate(application._id, {
      status: "Ready to Apply",
    });

    /* =======================================================
       RETURN
    ======================================================= */

    return {
      success: true,
      data: serialize(analysis),
    };
  } catch (error) {
    console.error("Gemini Analysis Error:", error);

    return {
      success: false,
      message: "Gemini analysis failed.",
    };
  }
}

